import type { Metadata } from "next";
import Link from "next/link";
import type { ReactNode } from "react";
import { notFound } from "next/navigation";
import { auditLabel } from "@/components/sections";
import { AuthorBadge, Card, Score } from "@/components/ui";
import { MAIN_APP_URL, getMedia, imageUrl, type MediaDetail } from "@/lib/admin-data";
import { requireAdmin } from "@/lib/auth";
import { VIBES, isVibe } from "@/lib/captions";
import { formatDate, formatDateTime, timeAgo } from "@/lib/format";
import { listChains } from "@/lib/studio-data";
import { isUuid } from "@/lib/validate";
import { CaptionActions, ContextEditor, DeletePost, GenerateCaptions } from "./MediaControls";

// Server actions on this page run a prompt chain, which can take a while.
export const maxDuration = 60;

export const metadata: Metadata = { title: "Post" };

export default async function MediaDetailPage(props: PageProps<"/media/[id]">) {
  const { id } = await props.params;
  const { supabase } = await requireAdmin(`/media/${id}`);
  if (!isUuid(id)) notFound();
  const searchParams = await props.searchParams;

  const [post, allChains] = await Promise.all([getMedia(supabase, id), listChains(supabase)]);
  if (!post) notFound();
  const chains = allChains.filter((c) => c.runnable).map((c) => ({ id: c.id, name: c.name }));

  const votes = post.captions.reduce((sum, c) => sum + c.upvotes + c.downvotes, 0);
  const ai = post.captions.filter((c) => c.author_type === "ai");
  const human = post.captions.filter((c) => c.author_type === "human");

  return (
    <>
      <Link href="/media" className="mb-4 inline-block text-sm text-muted hover:text-foreground">
        ← All media
      </Link>
      {searchParams.created && (
        <p role="status" className="mb-4 rounded-full bg-powder px-5 py-2.5 text-sm font-medium text-human-ink">
          Post created with {ai.length} Gemini captions. It&apos;s now live in the main app.
        </p>
      )}

      <div className="grid grid-cols-1 gap-5 lg:grid-cols-[minmax(0,380px)_minmax(0,1fr)]">
        <div className="space-y-5">
          <Card bodyClassName="p-0">
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={imageUrl(post.image_path)} alt={post.context ?? "Post photo"} className="w-full rounded-[20px] bg-powder object-contain" />
            <div className="space-y-4 p-5">
              <div className="flex flex-wrap items-center justify-between gap-2 text-sm">
                <span>
                  by{" "}
                  <Link href={`/users/${post.owner_id}`} className="font-medium hover:underline">
                    {post.owner_name}
                  </Link>
                </span>
                <a href={`${MAIN_APP_URL}/g/${post.id}`} target="_blank" rel="noreferrer" className="text-xs font-medium text-human hover:underline">
                  View in app ↗
                </a>
              </div>
              <ContextEditor generationId={post.id} context={post.context} />
            </div>
          </Card>

          <Card title="Generation record" description="Read-only history of how this post was made">
            <dl className="space-y-3 text-sm">
              <Row label="Posted">{formatDateTime(post.created_at)}</Row>
              <Row label="Challenge day">
                {formatDate(`${post.challenge_date}T12:00:00Z`)}
                {post.daily_prompt && <span className="block text-xs text-muted">“{post.daily_prompt}”</span>}
              </Row>
              <Row label="Caption voice">{isVibe(post.vibe) ? VIBES[post.vibe].label : post.vibe}</Row>
              <Row label="Photo source">
                {post.image_source === "ai" ? "Generated by AI" : "Uploaded"}
                {post.image_prompt && <span className="block text-xs text-muted">“{post.image_prompt}”</span>}
              </Row>
              <Row label="Model">
                <code className="text-xs">{post.model}</code>
              </Row>
            </dl>
            <details className="mt-4 group">
              <summary className="cursor-pointer text-xs font-medium text-human">Show the exact prompt sent to Gemini</summary>
              <pre className="mt-2 max-h-80 overflow-auto whitespace-pre-wrap rounded-[16px] bg-background p-3 text-xs leading-relaxed ring-1 ring-line">
                {post.prompt}
              </pre>
            </details>
          </Card>

          <Card title="Danger zone">
            <DeletePost generationId={post.id} captions={post.captions.length} votes={votes} />
          </Card>
        </div>

        <div className="space-y-5">
          <Card
            title={`Gemini captions (${ai.length})`}
            description="Edit or delete any AI caption. Every change is logged."
            action={<GenerateCaptions generationId={post.id} chains={chains} />}
          >
            <CaptionTable captions={ai} generationId={post.id} editable scene={post.context ?? ""} />
          </Card>
          <Card title={`Human captions (${human.length})`} description="Written by students. Admins can delete these, but not reword them.">
            <CaptionTable captions={human} generationId={post.id} editable={false} scene={post.context ?? ""} />
          </Card>
          <Card title="Change history" description="Admin edits to this post">
            {post.history.length ? (
              <ul className="space-y-3 text-sm">
                {post.history.map((h, i) => (
                  <li key={i}>
                    <p>
                      <span className="font-medium">{h.admin_name ?? "Deleted admin"}</span>{" "}
                      <span className="text-muted">{auditLabel(h.action)}</span>{" "}
                      <time className="text-xs text-subtle" dateTime={h.created_at}>
                        {timeAgo(h.created_at)}
                      </time>
                    </p>
                    {"old_text" in h.details && (
                      <p className="mt-1 text-xs text-muted">
                        <span className="line-through">“{String(h.details.old_text)}”</span> → “{String(h.details.new_text)}”
                      </p>
                    )}
                    {"text" in h.details && <p className="mt-1 text-xs text-muted line-through">“{String(h.details.text)}”</p>}
                    {"old_context" in h.details && (
                      <p className="mt-1 text-xs text-muted">
                        <span className="line-through">{String(h.details.old_context ?? "(none)")}</span> →{" "}
                        {String(h.details.new_context ?? "(none)")}
                      </p>
                    )}
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-muted">No admin changes yet.</p>
            )}
          </Card>
        </div>
      </div>
    </>
  );
}

function Row({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="grid grid-cols-[110px_1fr] gap-3">
      <dt className="text-muted">{label}</dt>
      <dd>{children}</dd>
    </div>
  );
}

function CaptionTable({
  captions,
  generationId,
  editable,
  scene,
}: {
  captions: MediaDetail["captions"];
  generationId: string;
  editable: boolean;
  // Starting text for "Save as example": what the photo shows.
  scene: string;
}) {
  if (!captions.length) return <p className="text-sm text-muted">None.</p>;
  return (
    <ul className="divide-y divide-line">
      {[...captions]
        .sort((a, b) => b.score - a.score)
        .map((c) => (
          <li key={c.id} className="py-3 first:pt-0 last:pb-0">
            <div className="flex items-start gap-3">
              <p className="min-w-0 flex-1 text-sm">“{c.text}”</p>
              <Score score={c.score} up={c.upvotes} down={c.downvotes} />
            </div>
            <div className="mt-1 flex flex-wrap items-center gap-2 text-xs text-subtle">
              <AuthorBadge type={c.author_type} />
              {c.author_type === "human" && (
                <Link href={`/users/${c.author_id}`} className="hover:underline">
                  {c.author_name}
                </Link>
              )}
              <span>{formatDateTime(c.created_at)}</span>
              {c.generated_by && <span>· added by {c.generated_by}</span>}
              {c.upvotes + c.downvotes > 0 && (
                <Link href={`/votes?caption=${c.id}`} className="hover:underline">
                  · see votes
                </Link>
              )}
            </div>
            {c.extra_prompt && (
              <details className="mt-1">
                <summary className="cursor-pointer text-xs text-human">Prompt for this caption ({c.extra_model})</summary>
                <pre className="mt-1 max-h-48 overflow-auto whitespace-pre-wrap rounded-[12px] bg-background p-2 text-[11px] ring-1 ring-line">
                  {c.extra_prompt}
                </pre>
              </details>
            )}
            <CaptionActions
              captionId={c.id}
              generationId={generationId}
              text={c.text}
              editable={editable}
              votes={c.upvotes + c.downvotes}
              scene={scene}
            />
          </li>
        ))}
    </ul>
  );
}
